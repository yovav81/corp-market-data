def write(path, specs):
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f); w.writerow(["security_id", "name", "issuer_model", "pay_date", "principal_pct", "coupon_pct", "source"])
        for s in specs:
            for x, p, c in build(s):
                w.writerow([s["id"], s["name"], s["issuer"], x.isoformat(), p, c, s["source"]])


