def build(spec):
    """first: (תאריך, ריבית תקופה ראשונה באחוזים) או None; days: [(חודש, יום)] של תשלומי הריבית; last: תשלום אחרון;
    start: מועד הריבית הרגילה הראשון; princ: {תאריך: אחוז קרן}."""
    per = spec["rate"] / len(spec["days"])
    dates = {}
    if spec.get("first"): dates[spec["first"][0]] = spec["first"][1]
    y = spec["start"].year
    while y <= spec["last"].year:
        for m, d in spec["days"]:
            x = D(y, m, d)
            if spec["start"] <= x <= spec["last"] and x not in dates: dates[x] = per
        y += 1
    for x in spec["princ"]: dates.setdefault(x, 0.0)
    rows = [(x, spec["princ"].get(x, 0.0), round(c, 6)) for x, c in sorted(dates.items())]
    assert abs(sum(r[1] for r in rows) - 100) < 0.06, (spec["id"], sum(r[1] for r in rows))
    return rows


